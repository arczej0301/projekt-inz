import React, { useState, useMemo, useEffect } from 'react'
import { useFinance } from '../../hooks/useFinance'
import CustomSelect from '../common/CustomSelect'
import { db } from '../../config/firebase'
import { collection, query, where, getDocs, orderBy, limit } from 'firebase/firestore'
import './FinanceComponents.css'

const ExpensesTab = ({ transactions }) => {
  const { expenseCategories, addTransaction } = useFinance()
  
  // Stan dla sortowania i filtrowania
  const [sortOption, setSortOption] = useState('date_desc')
  const [filterOption, setFilterOption] = useState('all')
  
  // Stan dla wybranego okresu
  const [period, setPeriod] = useState('yearly') // yearly, quarterly, monthly
  
  const [showAddForm, setShowAddForm] = useState(() => {
    return localStorage.getItem('openExpenseForm') === 'true';
  })

  // Otwieranie formularza z localStorage
  useEffect(() => {
    const shouldOpenForm = localStorage.getItem('openExpenseForm');
    if (shouldOpenForm === 'true') {
      setShowAddForm(true);
      localStorage.removeItem('openExpenseForm');
    }
  }, []);

  const [newTransaction, setNewTransaction] = useState({
    type: 'expense',
    category: '',
    amount: '',
    description: '',
    date: new Date().toISOString().split('T')[0]
  })

  const [partsData, setPartsData] = useState({})

  // Pobierz tylko części z Firestore
  useEffect(() => {
    const fetchPartsData = async () => {
      const garageTransactions = transactions.filter(
        t => t.autoGenerated && t.source === 'garage' && t.sourceId
      )

      if (garageTransactions.length === 0) {
        setPartsData({})
        return
      }

      const partsMap = {}

      for (const transaction of garageTransactions) {
        try {
          const repairsRef = collection(db, 'repairs')
          const q = query(
            repairsRef,
            where('machineId', '==', transaction.sourceId)
          )

          const querySnapshot = await getDocs(q)

          if (!querySnapshot.empty) {
            const repairs = []
            querySnapshot.forEach((doc) => {
              const repairData = doc.data()
              repairs.push({
                ...repairData,
                id: doc.id,
                date: repairData.date || repairData.createdAt?.toDate?.() || new Date()
              })
            })

            repairs.sort((a, b) => new Date(b.date) - new Date(a.date))
            const latestRepair = repairs[0]

            if (latestRepair.parts && latestRepair.parts.trim() !== '') {
              partsMap[transaction.id] = latestRepair.parts.trim()
            } else {
              partsMap[transaction.id] = null
            }
          } else {
            partsMap[transaction.id] = null
          }
        } catch (error) {
          console.error('Błąd pobierania części:', error)
          partsMap[transaction.id] = null
        }
      }

      setPartsData(partsMap)
    }

    fetchPartsData()
  }, [transactions])

  // Funkcja formatowania waluty
  const formatCurrency = (amount) => {
    if (amount === null || amount === undefined || isNaN(amount)) {
      return '0,00 zł'
    }

    const numAmount = parseFloat(amount)
    const formatted = numAmount.toFixed(2).replace('.', ',').replace(/\B(?=(\d{3})+(?!\d))/g, ' ')
    return `${formatted} zł`
  }

  // Opcje dla selektora okresu
  const periodOptions = [
    { value: 'yearly', label: 'Rok', icon: '📈' },
    { value: 'quarterly', label: 'Kwartał', icon: '📊' },
    { value: 'monthly', label: 'Miesiąc', icon: '📅' }
  ]

  // Opcje sortowania i filtrowania
  const sortOptions = [
    { value: 'date_desc', label: 'Najnowsze' },
    { value: 'date_asc', label: 'Najstarsze' },
    { value: 'amount_desc', label: 'Największe kwoty' },
    { value: 'amount_asc', label: 'Najmniejsze kwoty' },
    { value: 'category', label: 'Kategoria A-Z' }
  ]

  const filterOptions = [
    { value: 'all', label: 'Wszystkie kategorie' },
    { value: 'zwierzeta', label: 'Zwierzęta' },
    { value: 'maszyny', label: 'Maszyny' },
    { value: 'zboza', label: 'Zboża' },
    { value: 'nawozy_nasiona', label: 'Nawozy i nasiona' },
    { value: 'pasze', label: 'Pasze' },
    { value: 'paliwo', label: 'Paliwo' },
    { value: 'sprzet_czesci', label: 'Sprzęt i części' },
    { value: 'naprawa_konserwacja', label: 'Naprawa i konserwacja' },
    { value: 'auto', label: 'Auto-generowane' },
    { value: 'manual', label: 'Ręczne' }
  ]

  // Przygotuj opcje dla CustomSelect
  const categoryOptions = expenseCategories.map(cat => ({
    value: cat.id,
    label: cat.name,
    icon: cat.icon
  }))

  // Funkcja do pobierania daty transakcji
  const getTransactionDate = (t) => {
    if (t.date?.toDate) return t.date.toDate()
    if (t.date instanceof Date) return t.date
    if (typeof t.date === 'string') return new Date(t.date)
    if (t.createdAt?.toDate) return t.createdAt.toDate()
    return new Date(t.date || t.createdAt || 0)
  }

  // Funkcja do filtrowania transakcji według okresu
  const getFilteredTransactionsByPeriod = useMemo(() => {
    const now = new Date()
    
    let startDate = new Date()
    let endDate = new Date()
    
    switch (period) {
      case 'yearly':
        // ROK WSTECZ (od dzisiaj minus 365 dni do dzisiaj)
        endDate = now
        startDate = new Date(now.getTime() - 365 * 24 * 60 * 60 * 1000)
        break
        
      case 'quarterly':
        // OSTATNI PEŁNY KWARTAŁ
        const currentYear = now.getFullYear()
        const currentMonth = now.getMonth()
        const previousQuarter = Math.floor((currentMonth - 1) / 3)
        
        if (previousQuarter < 0) {
          startDate = new Date(currentYear - 1, 9, 1)
          endDate = new Date(currentYear - 1, 11, 31, 23, 59, 59)
        } else {
          const quarterStartMonth = previousQuarter * 3
          startDate = new Date(currentYear, quarterStartMonth, 1)
          endDate = new Date(currentYear, quarterStartMonth + 3, 0, 23, 59, 59)
        }
        break
        
      case 'monthly':
        // OSTATNI PEŁNY MIESIĄC
        const currentYearNow = now.getFullYear()
        const currentMonthNow = now.getMonth()
        
        if (currentMonthNow === 0) {
          startDate = new Date(currentYearNow - 1, 11, 1)
          endDate = new Date(currentYearNow - 1, 11, 31, 23, 59, 59)
        } else {
          startDate = new Date(currentYearNow, currentMonthNow - 1, 1)
          endDate = new Date(currentYearNow, currentMonthNow, 0, 23, 59, 59)
        }
        break
        
      default:
        endDate = now
        startDate = new Date(now.getTime() - 365 * 24 * 60 * 60 * 1000)
    }
    
    return transactions.filter(transaction => {
      const transactionDate = getTransactionDate(transaction)
      return transactionDate >= startDate && transactionDate <= endDate
    })
  }, [transactions, period])
  
  // Etykiety dla okresu
  const getPeriodLabel = () => {
    const now = new Date()
    const monthNames = ['Styczeń', 'Luty', 'Marzec', 'Kwiecień', 'Maj', 'Czerwiec', 
                       'Lipiec', 'Sierpień', 'Wrzesień', 'Październik', 'Listopad', 'Grudzień']
    
    switch (period) {
      case 'yearly':
        const oneYearAgo = new Date(now.getTime() - 365 * 24 * 60 * 60 * 1000)
        const startDay = oneYearAgo.getDate()
        const startMonth = monthNames[oneYearAgo.getMonth()]
        const startYear = oneYearAgo.getFullYear()
        const endDay = now.getDate()
        const endMonth = monthNames[now.getMonth()]
        const endYear = now.getFullYear()
        
        return `${startDay} ${startMonth.toLowerCase()} ${startYear} - ${endDay} ${endMonth.toLowerCase()} ${endYear}`
        
      case 'quarterly':
        const currentMonth = now.getMonth()
        const quarterNames = ['I kwartał', 'II kwartał', 'III kwartał', 'IV kwartał']
        
        let quarterIndex = Math.floor((currentMonth - 1) / 3)
        let year = now.getFullYear()
        
        if (quarterIndex < 0) {
          quarterIndex = 3
          year = year - 1
        }
        
        return `${quarterNames[quarterIndex]} ${year}`
        
      case 'monthly':
        let monthIndex = now.getMonth() - 1
        let monthYear = now.getFullYear()
        
        if (monthIndex < 0) {
          monthIndex = 11
          monthYear = monthYear - 1
        }
        
        return `${monthNames[monthIndex]} ${monthYear}`
        
      default:
        return `Ostatnie 12 miesięcy`
    }
  }

  // Sortowanie i filtrowanie transakcji (już po filtrowaniu okresu)
  const sortedTransactions = useMemo(() => {
    let filtered = [...getFilteredTransactionsByPeriod]

    // Filtrowanie kategorii
    if (filterOption !== 'all') {
      if (filterOption === 'auto') {
        filtered = filtered.filter(t => t.autoGenerated)
      } else if (filterOption === 'manual') {
        filtered = filtered.filter(t => !t.autoGenerated)
      } else {
        filtered = filtered.filter(t => t.category === filterOption)
      }
    }

    // Sortowanie
    return filtered.sort((a, b) => {
      switch (sortOption) {
        case 'date_asc':
          return getTransactionDate(a).getTime() - getTransactionDate(b).getTime()

        case 'date_desc':
          return getTransactionDate(b).getTime() - getTransactionDate(a).getTime()

        case 'amount_desc':
          return b.amount - a.amount

        case 'amount_asc':
          return a.amount - b.amount

        case 'category':
          const catA = expenseCategories.find(c => c.id === a.category)?.name || a.category
          const catB = expenseCategories.find(c => c.id === b.category)?.name || b.category
          return catA.localeCompare(catB)

        default:
          return getTransactionDate(b).getTime() - getTransactionDate(a).getTime()
      }
    })
  }, [getFilteredTransactionsByPeriod, sortOption, filterOption, expenseCategories])

  const handleAddTransaction = async (e) => {
    e.preventDefault()
    if (!newTransaction.category || !newTransaction.amount || !newTransaction.description) {
      alert('Proszę wypełnić wszystkie pola')
      return
    }

    const result = await addTransaction(newTransaction)
    if (result.success) {
      setShowAddForm(false)
      setNewTransaction({
        type: 'expense',
        category: '',
        amount: '',
        description: '',
        date: new Date().toISOString().split('T')[0]
      })
    } else {
      alert('Błąd przy dodawaniu transakcji: ' + result.error)
    }
  }

  const handleCloseForm = () => {
    setShowAddForm(false);
    localStorage.removeItem('openExpenseForm');
  };

  const totalExpenses = sortedTransactions.reduce((sum, t) => sum + t.amount, 0)

  return (
    <div className="expenses-tab">
  {/* SELEKTOR OKRESU - NOWY UKŁAD */}
  <div className="expenses-period-selector">
    <div className="period-left-section">
      <div className="period-header">
        <h3>Koszty</h3>
        <p className="period-label">{getPeriodLabel()}</p>
      </div>
      
      <div className="period-buttons">
        {periodOptions.map(option => (
          <button
            key={option.value}
            onClick={() => setPeriod(option.value)}
            className={`period-button ${period === option.value ? 'active' : ''}`}
          >
            <span className="period-icon">{option.icon}</span>
            <span>{option.label}</span>
          </button>
        ))}
      </div>
    </div>
    
    <div className="period-right-section">
      {/* SEKCJA SORTOWANIA I FILTROWANIA */}
      <div className="sort-filter-section">
        <label>Sortowanie</label>

        {/* PIERWSZY select - Filtrowanie */}
        <select
          className="control-select"
          value={filterOption}
          onChange={(e) => setFilterOption(e.target.value)}
        >
          <option value="all">Wszystkie kategorie</option>
          {expenseCategories.map(cat => (
            <option key={cat.id} value={cat.id}>
              {cat.name}
            </option>
          ))}
          <option value="auto">Auto-generowane</option>
          <option value="manual">Ręczne</option>
        </select>

        {/* DRUGI select - Sortowanie */}
        <select
          className="control-select"
          value={sortOption}
          onChange={(e) => setSortOption(e.target.value)}
        >
          {sortOptions.map(option => (
            <option key={option.value} value={option.value}>
              {option.label}
            </option>
          ))}
        </select>

        <button
          className="btn btn-primary"
          onClick={() => setShowAddForm(true)}
        >
          + Dodaj koszt
        </button>
      </div>
    </div>
  </div>

  <div className="total-summary">
    Łączne koszty dla wybranego okresu: <strong>{formatCurrency(totalExpenses)}</strong>
    {filterOption !== 'all' && (
      <span className="filter-info">
        (Filtr: {filterOptions.find(f => f.value === filterOption)?.label})
      </span>
        )}
      </div>

      {showAddForm && (
        <div className="modal-overlay">
          <div className="modal-content">
            <div className="modal-header">
              <h4>Dodaj nowy koszt</h4>
              <button className="close-btn" onClick={handleCloseForm}>×</button>
            </div>
            <form onSubmit={handleAddTransaction}>
              <div className="form-group">
                <label>Kategoria *</label>
                <CustomSelect
                  options={categoryOptions}
                  value={newTransaction.category}
                  onChange={(value) => setNewTransaction(prev => ({ ...prev, category: value }))}
                  placeholder="Wybierz kategorię..."
                  searchable={true}
                />
              </div>

              <div className="form-group">
                <label>Kwota (zł) *</label>
                <input
                  type="number"
                  step="0.01"
                  value={newTransaction.amount}
                  onChange={(e) => setNewTransaction(prev => ({ ...prev, amount: e.target.value }))}
                  required
                />
              </div>

              <div className="form-group">
                <label>Opis *</label>
                <input
                  type="text"
                  value={newTransaction.description}
                  onChange={(e) => setNewTransaction(prev => ({ ...prev, description: e.target.value }))}
                  required
                />
              </div>

              <div className="form-group">
                <label>Data</label>
                <input
                  type="date"
                  value={newTransaction.date}
                  onChange={(e) => setNewTransaction(prev => ({ ...prev, date: e.target.value }))}
                />
              </div>

              <div className="form-actions">
                <button type="button" className="btn btn-secondary" onClick={handleCloseForm}>
                  Anuluj
                </button>
                <button type="submit" className="btn btn-primary">
                  Dodaj koszt
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      <div className="transactions-table">
        {sortedTransactions.length === 0 ? (
          <div className="no-data-with-period">
            <p>Brak transakcji kosztowych dla wybranego okresu</p>
            <p style={{ fontSize: '0.9rem', marginTop: '10px' }}>
              Wybierz inny okres lub dodaj nową transakcję
            </p>
          </div>
        ) : (
          <table>
            <thead>
              <tr>
                <th>Data</th>
                <th>Kategoria</th>
                <th>Opis</th>
                <th>Kwota</th>
                <th>Szczegóły</th>
                <th>Typ</th>
              </tr>
            </thead>
            <tbody>
              {sortedTransactions.map(transaction => {
                const parts = partsData[transaction.id]

                return (
                  <tr key={transaction.id}>
                    <td>{getTransactionDate(transaction).toLocaleDateString('pl-PL')}</td>
                    <td>
                      <span className="category-with-icon">
                        <span className="icon">
                          {expenseCategories.find(cat => cat.id === transaction.category)?.icon || '📉'}
                        </span>
                        {expenseCategories.find(cat => cat.id === transaction.category)?.name || transaction.category}
                      </span>
                    </td>
                    <td>{transaction.description}</td>
                    <td className="amount negative">-{formatCurrency(transaction.amount)}</td>

                    <td>
                      {transaction.productName ? (
                        <span className="product-badge">
                          {transaction.productName}
                          {transaction.quantity && ` (${transaction.quantity} ${transaction.unit})`}
                        </span>
                      ) : transaction.autoGenerated ? (
                        transaction.source === 'garage' ? (
                          <div className="parts-container">
                            {parts ? (
                              <span className="parts-badge">{parts}</span>
                            ) : (
                              <span className="no-parts">Brak</span>
                            )}
                          </div>
                        ) : (
                          <span className="auto-details">Transakcja automatyczna</span>
                        )
                      ) : (
                        <span className="manual-details">Brak szczegółów</span>
                      )}
                    </td>

                    <td>
                      {transaction.autoGenerated ? (
                        <span className="auto-badge">Auto</span>
                      ) : (
                        <span className="manual-badge">Ręczne</span>
                      )}
                    </td>
                  </tr>
                )
              })}
            </tbody>
          </table>
        )}
      </div>
    </div>
  )
}

export default ExpensesTab